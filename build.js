import { readFile, writeFile } from 'node:fs/promises';
const root = import.meta.dirname;
const geometry = (await readFile(`${root}/geometry.js`, 'utf8')).replace(/^export /gm, '');
const app = (await readFile(`${root}/app.js`, 'utf8')).replace(/^import .*?;\s*/, '');
const worker = await readFile(`${root}/export-worker-source.js`, 'utf8');
await writeFile(`${root}/studio.js`, `/* Generated by node build.js. Edit app.js and geometry.js. */\n(()=>{\n'use strict';\n${geometry}\n${app}\n})();\n`);
await writeFile(`${root}/export-worker.js`, `/* Generated by node build.js. Edit export-worker-source.js and geometry.js. */\n(()=>{\n'use strict';\n${geometry}\n${worker}\n})();\n`);
console.log('Built Clock Factory browser and export worker scripts.');
